// Writes src/util/letters.mbt: the code points of `[\p{L}\p{N}]` as the running node sees them.
// pele checks font names with that class, and MoonBit's core library has no Unicode property tables.
//
// Usage: node scripts/gen-letters.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const re = /[\p{L}\p{N}]/u;
const ranges = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (!re.test(String.fromCodePoint(cp))) continue;
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}
let prev = 0;
const parts = [];
for (const [a, b] of ranges) {
  parts.push((a - prev).toString(36), (b - a).toString(36));
  prev = b;
}
const lines = [];
for (let i = 0; i < parts.length; i += 24) lines.push('  #|' + parts.slice(i, i + 24).join(' '));

const source = `// Generated by scripts/gen-letters.mjs from node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.

///|
/// Ranges of \`[\\p{L}\\p{N}]\`: base-36 gaps from the previous range's end and lengths, alternating.
let letter_ranges_packed : String =
${lines.join('\n')}

///|
let letter_ranges : Array[Int] = {
  let out = []
  let mut prev = 0
  let parts = letter_ranges_packed.replace_all(old="\\n", new=" ").split(" ").to_array()
  for i = 0; i + 1 < parts.length(); i = i + 2 {
    let start = prev + base36_value(parts[i])
    prev = start + base36_value(parts[i + 1])
    out.push(start)
    out.push(prev)
  }
  out
}

///|
fn base36_value(digits : StringView) -> Int {
  let mut value = 0
  for c in digits {
    let d = if c >= '0' && c <= '9' { c.to_int() - '0'.to_int() } else { c.to_int() - 'a'.to_int() + 10 }
    value = value * 36 + d
  }
  value
}

///|
/// Whether the code point is a letter or a number, as \`[\\p{L}\\p{N}]\` with the \`u\` flag sees it.
pub fn is_letter_or_number(code_point : Int) -> Bool {
  let mut lo = 0
  let mut hi = letter_ranges.length() / 2 - 1
  while lo <= hi {
    let mid = (lo + hi) / 2
    if code_point < letter_ranges[mid * 2] {
      hi = mid - 1
    } else if code_point > letter_ranges[mid * 2 + 1] {
      lo = mid + 1
    } else {
      return true
    }
  }
  false
}
`;
writeFileSync(join(root, 'src/util/letters.mbt'), source);
